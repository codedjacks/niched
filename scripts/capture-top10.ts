/** bun scripts/capture-top10.ts — builds src/game/top10-espn.ts from ESPN season leaderboards.
 * A list is kept only when ESPN's order is verifiably sorted by the stat and #10 isn't tied with #11. */
const sport = { nba: "basketball", nfl: "football", mlb: "baseball", nhl: "hockey" } as const;
type L = keyof typeof sport;
const METRICS: Record<L, [string, string, string][]> = {
  nba: [["offensive.avgPoints", "points per game", "PPG"], ["general.avgRebounds", "rebounds per game", "RPG"], ["offensive.avgAssists", "assists per game", "APG"], ["defensive.avgSteals", "steals per game", "SPG"], ["defensive.avgBlocks", "blocks per game", "BPG"], ["offensive.threePointFieldGoalsMade", "three-pointers made", "3PM"]],
  nfl: [["passing.passingYards", "passing yards", "yards"], ["passing.passingTouchdowns", "passing TDs", "TD"], ["rushing.rushingYards", "rushing yards", "yards"], ["rushing.rushingTouchdowns", "rushing TDs", "TD"], ["receiving.receivingYards", "receiving yards", "yards"], ["receiving.receptions", "receptions", "rec"], ["defensive.sacks", "sacks", "sacks"]],
  mlb: [["batting.homeRuns", "home runs", "HR"], ["batting.hits", "hits", "H"], ["batting.RBIs", "RBIs", "RBI"], ["batting.stolenBases", "stolen bases", "SB"], ["pitching.strikeouts", "pitcher strikeouts", "K"], ["pitching.wins", "pitcher wins", "W"], ["pitching.saves", "saves", "SV"]],
  nhl: [["offensive.goals", "goals", "goals"], ["offensive.assists", "assists", "assists"], ["offensive.points", "points", "points"]],
};
const LAST: Record<L, number> = { nba: 2026, nfl: 2025, mlb: 2026, nhl: 2026 };
const FIRST = 2003;
const label = (l: L, y: number) => (l === "nba" || l === "nhl" ? `${y - 1}-${String(y % 100).padStart(2, "0")}` : String(y));

async function read(url: string) {
  for (let t = 0; t < 3; t++) {
    try { const r = await fetch(url, { signal: AbortSignal.timeout(20000) }); if (r.ok) return r.json(); } catch { /* retry */ }
  }
  return null;
}
const out: { title: string; league: string; unit: string; rows: string }[] = [];
const jobs: (() => Promise<void>)[] = [];
for (const l of Object.keys(sport) as L[]) for (let y = FIRST; y <= LAST[l]; y++) for (const [sort, name, unit] of METRICS[l]) {
  jobs.push(async () => {
    const d = await read(`https://site.web.api.espn.com/apis/common/v3/sports/${sport[l]}/${l}/statistics/byathlete?season=${y}&seasontype=2&limit=11&sort=${sort}:desc`);
    if (!d?.athletes?.length || d.athletes.length < 11) return;
    const [cat, metric] = sort.split(".");
    const ci = (d.categories ?? []).findIndex((c: { name: string }) => c.name === cat);
    const mi = ci < 0 ? -1 : d.categories[ci].names.indexOf(metric);
    if (mi < 0) return;
    const vals: number[] = d.athletes.map((a: { categories: { name: string; values: number[] }[] }) => a.categories.find((c) => c.name === cat)?.values?.[mi] ?? NaN);
    if (vals.some((v) => !Number.isFinite(v)) || vals.some((v, i) => i > 0 && v > vals[i - 1]!) || vals[9] === vals[10] || vals[0]! <= 0) return;
    const names: string[] = d.athletes.slice(0, 10).map((a: { athlete: { displayName: string } }) => a.athlete.displayName);
    if (new Set(names).size !== 10) return;
    out.push({ title: `${l.toUpperCase()} ${label(l, y)} ${name}`, league: l.toUpperCase(), unit, rows: names.join(" | ") });
  });
}
for (let i = 0; i < jobs.length; i += 12) await Promise.all(jobs.slice(i, i + 12).map((j) => j()));
out.sort((a, b) => a.title.localeCompare(b.title));
const body = out.map((o) => `  l(${JSON.stringify(o.title)}, ${JSON.stringify(o.league)}, ${JSON.stringify(o.unit)}, ${JSON.stringify(o.rows)}),`).join("\n");
await Bun.write("src/game/top10-espn.ts", `// Generated by scripts/capture-top10.ts from ESPN regular-season leaderboards (verified sorted, no tie at #10).\n// Frozen: re-running may reorder; append new seasons in a new file instead.\nimport { l } from "./top10-list";\n\nexport const TOP10_ESPN = [\n${body}\n];\n`);
console.log(`Captured ${out.length} lists of ${jobs.length} tried.`);
